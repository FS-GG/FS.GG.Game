module Game.Render.Theme.Determinism.Program

// ADR GAME-RENDER-02.4 D11 (FS.GG.Game#789). Every line below is printed identically by .NET on Linux, .NET on
// Windows and node (through Fable), or the derivation is not deterministic. The last line is the summary the scripts
// read: `theme-determinism checks=N failed=F digest=D`.

open FS.GG.UI.Scene
open FS.GG.Game.Render

let private lines = ResizeArray<string>()
let mutable private checks = 0
let mutable private failed = 0

let private print (line: string) = lines.Add line

let private check (name: string) (passed: bool) =
    checks <- checks + 1

    if not passed then
        failed <- failed + 1
        print ("FAIL " + name)
    else
        print ("PASS " + name)

/// A digest over text, the same on both runtimes (int arithmetic below 2^31 only).
let private digestOf (text: string) (start: int) =
    let mutable d = start

    for c in text do
        d <- (d * 31 + int c) % 1000003

    d

let private colour r g b : Color =
    {
        Red = byte r
        Green = byte g
        Blue = byte b
        Alpha = 255uy
    }

let private resolved (theme: Theme) = Theme.hex theme @ (Theme.cssVariables theme)

[<EntryPoint>]
let main argv =
    let bake = argv |> Array.tryFindIndex ((=) "--bake")

    let fresh =
        match Theme.create ThemeSeed.classic [ ThemeAlgorithm.standard ] [] with
        | Ok theme -> theme
        | Error violations -> failwithf "classic does not resolve: %s" (violations |> List.map string |> String.concat "; ")

    match bake with
    | Some index ->
        let path = argv.[index + 1]

        let entries =
            Theme.aliases fresh
            |> List.map (fun alias ->
                match Theme.tryColour alias fresh with
                | Some c -> sprintf "        \"%s\", \"%s\"" alias (ThemeColour.hex c)
                | None -> sprintf "        \"%s\", \"%s\"" alias (Theme.cssVariables fresh |> List.find (fun (k, _) -> k = "--fsgg-" + alias.Replace('.', '-')) |> snd))

        let text =
            [
                "/// GENERATED by `dotnet run --project tests/Game.Render.Theme.Determinism -- --bake <this file>` (FS.GG.Game#789,"
                "/// ADR D11): the resolved aliases of each preset, baked at build time. A test derives each preset afresh and"
                "/// requires these values, so a change to an algorithm regenerates this file in the same PR (Q12)."
                "module internal FS.GG.Game.Render.ThemeBaked"
                ""
                "/// `Theme.classic`, alias by alias: `#rrggbb` for a colour, a number for a size."
                "let classic: (string * string) list ="
                "    ["
                yield! entries
                "    ]"
                ""
            ]
            |> String.concat "\n"

        System.IO.File.WriteAllText(path, text)
        printfn "baked %d aliases of classic into %s" entries.Length path
        0
    | None ->
        // 1. The baked preset equals a fresh derivation from its seed (Q12), alias by alias.
        print "# classic"

        for alias, value in Theme.hex Theme.classic do
            print (alias + " " + value)

        check "classic: the baked aliases equal a fresh derivation from ThemeSeed.classic" (resolved Theme.classic = resolved fresh)
        check "classic: every alias resolves" (Theme.aliases Theme.classic = Theme.aliases fresh)

        // 2. DTCG export is the same bytes, and export then import gives equal resolved hex for every alias.
        let dtcg = Theme.toDtcg Theme.classic
        print (sprintf "dtcg classic bytes=%d digest=%d" dtcg.Length (digestOf dtcg 7))
        let resolver = Theme.dtcgResolver Theme.presets
        print (sprintf "dtcg resolver bytes=%d digest=%d" resolver.Length (digestOf resolver 7))

        match Theme.ofDtcg [ ThemeAlgorithm.standard ] dtcg with
        | Ok back -> check "dtcg: export then import gives equal resolved hex for every alias" (resolved back = resolved Theme.classic)
        | Error _ -> check "dtcg: export then import resolves" false

        // 3. The CSS variables equal the Scene's colours.
        let css = Theme.cssVariables Theme.classic
        print (sprintf "css classic variables=%d digest=%d" css.Length (digestOf (css |> List.map (fun (k, v) -> k + ":" + v) |> String.concat ";") 7))

        check
            "css: every colour variable is the alias's #rrggbb"
            (Theme.hex Theme.classic
             |> List.forall (fun (alias, hex) -> css |> List.exists (fun (k, v) -> k = "--fsgg-" + alias.Replace('.', '-') && v = hex)))

        // 4. Custom seeds, derived at run time: 48 team hues around the circle, each resolved or refused the same way.
        let mutable customDigest = 7

        for k in 0..47 do
            let hue = float k * 7.5
            let team = ThemeColour.ofOklch { L = (if k % 2 = 0 then 0.62 else 0.85); C = 0.16; H = hue }
            let seed = ThemeSeed.classic |> ThemeSeed.named (sprintf "custom-%d" k) |> ThemeSeed.colour "team.0" team

            let line =
                match Theme.create seed [ ThemeAlgorithm.standard ] [] with
                | Ok theme -> sprintf "custom %d ok %s" k (Theme.hex theme |> List.map snd |> String.concat ",")
                | Error violations -> sprintf "custom %d refused %s" k (violations |> List.map (fun v -> v.Token) |> String.concat ",")

            customDigest <- digestOf line customDigest
            print line

        print (sprintf "custom digest=%d" customDigest)

        // 5. Gamut mapping over an OKLCH grid: lightness 0..1 by 0.02, chroma 0..0.4 by 0.02, hue 0..350 by 10.
        let mutable gridDigest = 7
        let mutable points = 0

        for l in 0..50 do
            for c in 0..20 do
                for h in 0..35 do
                    let shown = ThemeColour.ofOklch { L = float l / 50.0; C = float c * 0.02; H = float h * 10.0 }
                    gridDigest <- digestOf (ThemeColour.hex shown) gridDigest
                    points <- points + 1

        print (sprintf "gamut grid points=%d digest=%d" points gridDigest)

        // 6. The full 8-bit round trip: every sRGB colour survives toOklch then ofOklch.
        let mutable misses = 0
        let mutable firstMiss = ""

        for r in 0..255 do
            for g in 0..255 do
                for b in 0..255 do
                    let c = colour r g b
                    let back = ThemeColour.ofOklch (ThemeColour.toOklch c)

                    if back <> c then
                        if misses = 0 then
                            firstMiss <- ThemeColour.hex c + " -> " + ThemeColour.hex back

                        misses <- misses + 1

        print (sprintf "round trip colours=16777216 failures=%d%s" misses (if misses = 0 then "" else " first " + firstMiss))
        check "round trip: every 8-bit colour survives toOklch then ofOklch" (misses = 0)

        // 7. Contrast on the 8-bit values: the table's luminance of every grey, digested.
        let mutable greyDigest = 7

        for v in 0..255 do
            let ratio = ThemeColour.contrast (colour v v v) (colour 0 0 0)
            greyDigest <- (greyDigest * 31 + int (System.Math.Floor(ratio * 1000000.0))) % 1000003

        print (sprintf "grey contrast digest=%d" greyDigest)

        let mutable digest = 7

        for line in lines do
            digest <- digestOf line digest

        for line in lines do
            printfn "%s" line

        printfn "theme-determinism checks=%d failed=%d digest=%d" checks failed digest
        if failed = 0 then 0 else 1
